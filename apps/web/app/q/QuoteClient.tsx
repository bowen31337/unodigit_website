type Status = 'loading' | 'ready' | 'failed';

/** The ONE failure message for every non-success case: a missing parameter,
 * a bad signature, and an unknown id all render this, identically. The
 * Worker deliberately returns the same 403 for a bad signature and an
 * unknown id so quote ids are not enumerable — showing different copy here
 * would undo that. */
function FailedState() {
  return (
    <div className="flex min-h-[40vh] flex-col items-center justify-center text-center">
      <h1 className="type-title-1" style={{ color: 'var(--label)' }}>
        This link is not valid
      </h1>
      <p className="type-body mt-s5 max-w-md" style={{ color: 'var(--label-secondary)' }}>
        We could not open this quote. Links can expire or be mistyped — if you believe this is a
        mistake, please get in touch and we will send it again.
      </p>
    </div>
  );
}

function LoadingState() {
  return (
    <div className="flex min-h-[40vh] items-center justify-center">
      <p className="type-body" style={{ color: 'var(--label-secondary)' }}>
        Loading your quote…
      </p>
    </div>
  );
}

export default function QuoteClient() {
  const searchParams = useSearchParams();
  const id = searchParams.get('id');
  const sig = searchParams.get('sig');

  const [status, setStatus] = useState<Status>('loading');
  const [markdown, setMarkdown] = useState('');

  useEffect(() => {
    // A missing id or sig is refused locally — never sent to the Worker as an
    // empty or undefined signature. Same failure state as a 403.
    if (!id || !sig || !BOT_API) {
      setStatus('failed');
      return;
    }

    let cancelled = false;
    const controller = new AbortController();

    (async () => {
      try {
        const res = await fetch(
          `${BOT_API}/api/quote/${encodeURIComponent(id)}?sig=${encodeURIComponent(sig)}`,
          { signal: controller.signal },
        );
        if (!res.ok) {
          if (!cancelled) setStatus('failed');
          return;
        }
        const body = (await res.json().catch(() => null)) as QuoteDetailResponse | null;
        if (!body || typeof body.markdown !== 'string') {
          if (!cancelled) setStatus('failed');
          return;
        }
        if (!cancelled) {
          setMarkdown(body.markdown);
          setStatus('ready');
        }
      } catch {
        // Network failure, abort, or a malformed response all collapse into
        // the same state as a 403 — this page never distinguishes reasons.
        if (!cancelled) setStatus('failed');
      }
    })();

    return () => {
      cancelled = true;
      controller.abort();
    };
  }, [id, sig]);

  return (
    <section className="relative overflow-hidden pb-s12 pt-32 sm:pt-40">
      <GradientMesh soft={status !== 'ready'} fadeOut={status === 'ready'} />
      <div className="container relative z-[1]">
        {status === 'loading' && <LoadingState />}
        {status === 'failed' && <FailedState />}
        {status === 'ready' && (
          <div className="prose-apple mx-auto">
            <Markdown source={markdown} />
          </div>
        )}
      </div>
    </section>
  );
}
